# -*- coding: utf-8 -*-
"""
Сверка чисел документов с данными проекта.

В презентации такая проверка уже есть, и она не раз ловила расхождение:
вес приложения менялся, а слайд оставался со старым числом. В документах
чисел не меньше — 7 тақырып, 15 тапсырма, 47 жазба, — и разъедутся они
ровно так же тихо.

С версии 3.0 проверка ищет ещё и следы прежней версии: разделы, которых
в приложении больше нет («Сөздік бөлімі», спринт, 623 жазба). Числа такой
текст может и не содержать — а неправдой он от этого быть не перестаёт.

Скрипт не правит тексты, а показывает расхождения. Запускается сам
при сборке документов, отдельно — так:

    ../презентация/venv/bin/python сверка-чисел.py

Нужен свежий `npm run build` в корне: вес считается по сборке.
"""
import gzip
import json
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent


def факты() -> dict[str, int]:
    def читать(имя):
        return json.loads((ROOT / "src" / "data" / имя).read_text(encoding="utf-8"))

    темы = читать("lessons.json")["lessons"]
    шаги = [s for l in темы for s in l["steps"]]
    индекс = читать("audio-index.json")

    активы = ROOT / "dist" / "assets"
    вес = 0
    if активы.exists():
        главные = list(активы.glob("index-*.js")) + list(активы.glob("index-*.css"))
        вес = round(sum(len(gzip.compress(f.read_bytes())) for f in главные) / 1024)

    тесты = sum(len(re.findall(r"^test\(", f.read_text(encoding="utf-8"), re.M))
                for f in sorted((ROOT / "tools" / "tests").glob("*.test.ts")))
    контраст = subprocess.run([sys.executable, str(ROOT / "tools" / "contrast.py")],
                              capture_output=True, text=True).stdout

    return {
        "тақырып": len(темы),
        "тапсырма": len(шаги),
        "жазба": len(индекс.get("available", [])),
        "автотест": тесты,
        "тексеру": len(re.findall(r"нужно ≥", контраст)),
        "КБ": вес,
    }


# Числа, которые могут стоять в тексте помимо сверяемых: они тоже верные,
# но означают другое — заданий в одной теме бывает два или три.
ИСКЛЮЧЕНИЯ: dict[str, set[int]] = {
    "тақырып": set(),
    "тапсырма": {2, 3},
    "жазба": set(),
    "автотест": set(),
    "тексеру": set(),
    "КБ": set(),
}

ШАБЛОНЫ = {
    "тақырып": r"(\d+)\s+тақырып",
    "тапсырма": r"(\d+)\s+тапсырма\b",
    "жазба": r"(\d+)\s+жазба",
    "автотест": r"(\d+)\s+автотест",
    "тексеру": r"(\d+)\s+тексеру",
    "КБ": r"(\d+)\s*КБ",
    # Те же утверждения в русских версиях документов.
    "тақырып_ru": r"(\d+)\s+тем\b",
    "тапсырма_ru": r"(\d+)\s+задани",
    "жазба_ru": r"(\d+)\s+запис",
    "автотест_ru": r"(\d+)\s+автотест",
    "тексеру_ru": r"(\d+)\s+проверок контраста",
    "КБ_ru": r"(\d+)\s*КБ",
}

# Следы версии 2.0 — того, чего в приложении больше нет. Регистр важен:
# «сөздік-сөйлесулері» в объяснении названия — не раздел «Сөздік».
СТАРОЕ = [
    "Сабақтар жолы", "Жаттығу бөлімі", "Сөздік бөлімі", "Анықтама бөлімі",
    "спринт", "Спринт", "марапат", "XP", "ұпай", "SM-2", "623", "225 тапсырма",
    "26 сабақ", "орыс әріптерімен", "Tilashar-Setup-2.0.0", "Tilashar-portable",
    "Дорожка уроков", "Практика", "Словарь", "Справка", "наград", "623 запис",
    "225 заданий", "26 уроков", "русскими буквами",
    # С 3.0.1 проекту вернули исходное название.
    "Тілашар", "ТІЛАШАР", "Tilashar", "tilashar",
]


def листов(pdf: pathlib.Path) -> int:
    """Число страниц PDF без сторонних библиотек — по объектам /Type /Page."""
    b = pdf.read_bytes()
    return len(re.findall(rb"/Type\s*/Page[^s]", b))


# Где ещё записан объём документов. Число живёт отдельно от самих файлов
# и разъезжалось уже трижды — каждый раз молча.
ГДЕ_ОБЪЁМ = [
    (HERE / "ЧИТАТЬ-ПЕРВЫМ.md", r"(\d+)\s+страниц"),
]


def страницы_в_памятках() -> int:
    объёмы = {pdf.stem: листов(pdf) for pdf in sorted(HERE.glob("*.pdf"))}
    плохо = 0
    for памятка, шаблон in ГДЕ_ОБЪЁМ:
        if not памятка.exists():
            continue
        текст = памятка.read_text(encoding="utf-8-sig")
        нашлось = [int(м) for м in re.findall(шаблон, текст)]
        лишние = [n for n in нашлось if n not in объёмы.values()]
        if лишние:
            плохо += len(лишние)
            for n in лишние:
                print(f"  ✗ {памятка.name}: указано {n} стр., "
                      f"а в файлах {' и '.join(str(v) for v in sorted(set(объёмы.values())))}")
        elif нашлось:
            print(f"  ✓ {памятка.name}: {len(нашлось)} упоминаний объёма — все верны")
    return плохо


def текст(файл: pathlib.Path) -> str:
    import zipfile
    xml = zipfile.ZipFile(файл).read("word/document.xml").decode("utf-8")
    return re.sub(r"<[^>]+>", "", re.sub(r"</w:p>", "\n", xml))


def main() -> None:
    ф = факты()
    for ключ in list(ф):
        ф[f"{ключ}_ru"] = ф[ключ]
    for ключ in list(ИСКЛЮЧЕНИЯ):
        ИСКЛЮЧЕНИЯ[f"{ключ}_ru"] = ИСКЛЮЧЕНИЯ[ключ]
    print("Числа по данным проекта:")
    for k, v in ф.items():
        if not k.endswith("_ru"):
            print(f"  {k:10} {v}")

    плохо = 0
    документы = sorted(HERE.glob("*.docx"))
    print("\nСверка с документами:")
    for файл in документы:
        t = текст(файл)
        for ключ, шаблон in ШАБЛОНЫ.items():
            for найдено in {int(m) for m in re.findall(шаблон, t)}:
                if найдено == ф[ключ] or найдено in ИСКЛЮЧЕНИЯ[ключ]:
                    continue
                плохо += 1
                print(f"  ✗ {файл.name}: «{найдено} {ключ}», по данным {ф[ключ]}")
        for след in СТАРОЕ:
            # Целым словом: «Практика» иначе находилась внутри казахского
            # «Практикалық кеңестер».
            if re.search(rf"(?<!\w){re.escape(след)}(?!\w)", t):
                плохо += 1
                print(f"  ✗ {файл.name}: след прежней версии — «{след}»")

    print("\nСверка объёма с памятками:")
    плохо += страницы_в_памятках()

    if плохо:
        print(f"\nРасхождений: {плохо}. Поправить в текстах и пересобрать.")
        sys.exit(1)
    print(f"  ✓ числа и объём в {len(документы)} документах сходятся с данными, "
          f"следов прежней версии нет")


if __name__ == "__main__":
    main()
