# -*- coding: utf-8 -*-
"""
Сверка казахской и русской версий документов.

Русские документы — перевод казахских блок в блок. Пока их два файла,
они разъедутся: абзац допишут в один, а про второй забудут. Проверка
сравнивает не текст (он и должен быть разным), а скелет — последовательность
видов блоков, число пунктов в списках, размеры таблиц и имена рисунков.

Так же устроена сверка в презентации, и там это уже ловило пропуски.

    ../презентация/venv/bin/python сверка-структуры.py

Запускается сама при сборке документов.
"""
import importlib.util
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

ПАРЫ = [
    ("техническое.py", "техническое_ru.py"),
    ("руководство.py", "руководство_ru.py"),
]


def загрузить(имя: str):
    спека = importlib.util.spec_from_file_location(имя.replace(".py", ""), HERE / имя)
    модуль = importlib.util.module_from_spec(спека)
    спека.loader.exec_module(модуль)
    return модуль


def скелет(блок) -> tuple:
    """
    Что должно совпадать у двух языков. Текст сюда не входит — он разный,
    и в этом весь смысл. Входит форма: вид блока, сколько в нём пунктов,
    какого размера таблица, какой рисунок.
    """
    вид, данные = блок[0], блок[1]
    if вид in ("b", "b2"):
        return (вид, len(данные))
    if вид == "table":
        return (вид, len(данные), len(данные[0]))
    if вид == "img":
        return (вид, данные)          # имя файла рисунка обязано совпасть
    return (вид,)


def сверить(казахский: str, русский: str) -> int:
    kk, ru = загрузить(казахский), загрузить(русский)
    a = [скелет(б) for б in kk.БЛОКИ]
    b = [скелет(б) for б in ru.БЛОКИ]

    if len(a) != len(b):
        print(f"  ✗ {казахский}: {len(a)} блоков, {русский}: {len(b)}")
        return 1

    плохо = 0
    for i, (x, y) in enumerate(zip(a, b)):
        if x != y:
            плохо += 1
            print(f"  ✗ блок {i}: у казахского {x}, у русского {y}")
            if плохо >= 5:
                print("  … дальше не показываю")
                break
    if not плохо:
        print(f"  ✓ {казахский} и {русский}: {len(a)} блоков, скелет совпадает")
    return плохо


def main() -> None:
    плохо = sum(сверить(kk, ru) for kk, ru in ПАРЫ)
    if плохо:
        print("\nВерсии разъехались. Правку нужно внести в оба языка.")
        sys.exit(1)


if __name__ == "__main__":
    main()
