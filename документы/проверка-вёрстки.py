# -*- coding: utf-8 -*-
"""
Проверка вёрстки документов: не осталось ли пустых страниц.

Пустая страница получается не от небрежности, а от рисунка, который
не помещается на лист. Word такой рисунок не уменьшает — он его обрезает,
а всё, что было перед ним, выталкивает на предыдущую страницу. Заголовок
остаётся один, следующая страница уходит под обрезанную картинку.
Именно так и вышло: в руководстве 16-я страница содержала только заголовок
«7. Прогресті бақылау», а 17-я — обрезанный снимок «профиля» размером
800×5251 точек, то есть 47 сантиметров высоты на листе в 25,7.

По тексту такую страницу не поймать: страница с крупным рисунком и короткой
подписью выглядит так же пусто. Поэтому меряем долю закрашенного —
`чтец-pdf` отдаёт её вместе с текстом.

    ../презентация/venv/bin/python проверка-вёрстки.py

Запускается сам при сборке документов.
"""
import json
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
ЧТЕЦ = HERE / "чтец-pdf"

# Ниже этого страница пустая: на ней только колонтитул, может быть заголовок.
# Для сравнения: обычная страница с текстом даёт 7–20 %.
ПОРОГ = 0.03


def листы(pdf: pathlib.Path) -> list[dict]:
    вывод = subprocess.run([str(ЧТЕЦ), str(pdf)], check=True, capture_output=True).stdout
    return json.loads(вывод)


def main() -> None:
    плохо = 0
    for pdf in sorted(HERE.glob("*.pdf")):
        страницы = листы(pdf)
        # Последнюю не проверяем: документ кончается там, где кончается,
        # и короткое заключение на отдельном листе — это нормально.
        for номер, лист in enumerate(страницы[:-1], start=1):
            if лист["краска"] < ПОРОГ:
                плохо += 1
                текст = " ".join(лист["текст"].split())
                print(f"  ✗ {pdf.name}, стр. {номер}: почти пустая "
                      f"({лист['краска'] * 100:.1f} % закрашено) — «{текст[:50]}»")
        среднее = sum(л["краска"] for л in страницы) / len(страницы)
        print(f"  {'✓' if not плохо else ' '} {pdf.name}: {len(страницы)} стр., "
              f"заполнение в среднем {среднее * 100:.0f} %")

    if плохо:
        print(f"\nПустых страниц: {плохо}. Обычная причина — рисунок выше листа: "
              f"проверьте размеры в документы/скриншоты.")
        sys.exit(1)


if __name__ == "__main__":
    main()
