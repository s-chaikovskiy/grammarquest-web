# -*- coding: utf-8 -*-
"""
Подрезка пустого низа у скриншотов.

Кадр снимается ровно в экран телефона — 800×1720. Но экран урока короче
экрана, и нижняя треть кадра остаётся пустой заливкой. В документе такая
картинка занимает 15 сантиметров, из которых пять — пустота.

Срезаем снизу ряды, совпадающие с цветом фона, оставляя небольшое поле.
Верх не трогаем: там шапка, она всегда на месте.

    python3 документы/подрезать-скриншоты.py
"""
import pathlib

from PIL import Image

HERE = pathlib.Path(__file__).resolve().parent
СКРИНЫ = HERE / "скриншоты"
ПОЛЕ = 24          # сколько пустоты оставить под последним элементом
РАЗБРОС = 4        # на сколько ряд может отличаться от фона и всё ещё считаться пустым


def подрезать(файл: pathlib.Path) -> tuple[int, int]:
    им = Image.open(файл).convert("RGB")
    ш, в = им.size
    точки = им.load()
    фон = точки[ш // 2, в - 1]

    низ = в
    for y in range(в - 1, -1, -1):
        ряд = [точки[x, y] for x in range(0, ш, 8)]
        пусто = all(all(abs(c - f) <= РАЗБРОС for c, f in zip(п, фон)) for п in ряд)
        if not пусто:
            низ = min(в, y + 1 + ПОЛЕ)
            break

    if низ >= в:
        return в, в
    им.crop((0, 0, ш, низ)).save(файл)
    return в, низ


def main():
    for файл in sorted(СКРИНЫ.glob("[0-1][0-9]-*.png")):
        было, стало = подрезать(файл)
        см = 7.2 * стало / 800
        знак = "подрезан" if стало != было else "без пустоты"
        print(f"  {файл.name:26} {было:5} → {стало:5}  ({см:4.1f} см)  {знак}")


if __name__ == "__main__":
    main()
