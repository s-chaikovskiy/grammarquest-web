/**
 * Қошқар мүйіз — «рога барана».
 *
 * Самый узнаваемый казахский орнамент: пара встречных завитков. Рисуется
 * векторно и повторяется плиткой, поэтому весит десятки байт и остаётся
 * чётким на любом экране — в отличие от картинки, которую пришлось бы
 * держать в трёх размерах.
 *
 * Лежит фоном под содержимым и не перехватывает нажатия. Если по какой-то
 * причине не отрисуется, экран выглядит как обычно: орнамент украшает,
 * но ничего не сообщает.
 */
type Props = {
  /** Насколько заметен. По умолчанию — на грани различимости. */
  opacity?: number;
  /** Размер плитки в пикселях. */
  tile?: number;
  className?: string;
};

let seq = 0;

export default function Ornament({ opacity = 0.07, tile = 88, className }: Props) {
  // Свой идентификатор на каждый экземпляр: несколько орнаментов на странице
  // не должны делить одно определение плитки.
  const id = `ornament-${++seq}`;

  return (
    <svg
      className={`ornament${className ? ' ' + className : ''}`}
      aria-hidden
      focusable="false"
      style={{ opacity }}
    >
      <defs>
        <pattern id={id} width={tile} height={tile} patternUnits="userSpaceOnUse">
          {/*
            Мотив построен из двух зеркальных завитков и ромба между ними —
            так его чаще всего и выкладывают на войлоке. Линии одной толщины,
            без заливок: узор должен читаться как резьба, а не как наклейка.
          */}
          <g fill="none" stroke="currentColor" strokeWidth="1.5" strokeLinecap="round">
            <path d="M14 44c0-16 11-27 26-27 10 0 17 6 17 15 0 7-5 12-12 12-5 0-9-3-9-8" />
            <path d="M74 44c0-16-11-27-26-27-10 0-17 6-17 15 0 7 5 12 12 12 5 0 9-3 9-8" />
            <path d="M44 52l10 10-10 10-10-10z" />
            <path d="M8 76h72" strokeWidth="1" />
          </g>
        </pattern>
      </defs>
      <rect width="100%" height="100%" fill={`url(#${id})`} />
    </svg>
  );
}
