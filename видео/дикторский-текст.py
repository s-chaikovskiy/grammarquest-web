import json
import pathlib

ЖУРНАЛ = pathlib.Path(__file__).resolve().parent / "журнал-записи.json"
_журнал = json.loads(ЖУРНАЛ.read_text(encoding="utf-8"))

# Сколько тишины оставить до записи и после неё. До — меньше: нажатие
# кнопки и начало звука почти совпадают. После — больше: реплика должна
# отзвучать, прежде чем вступит диктор.
ЗАПАС_ДО = 0.30
ЗАПАС_ПОСЛЕ = 0.50


def _окна() -> list[tuple[float, float]]:
    сырые = sorted((с["t"] - ЗАПАС_ДО, с["t"] + с["длительность"] + ЗАПАС_ПОСЛЕ)
                   for с in _журнал["события"] if с["что"] == "звук")
    слитые: list[list[float]] = []
    for от, до in сырые:
        # Реплики Айши и учителя идут подряд: их окна сливаются в одно.
        if слитые and от <= слитые[-1][1]:
            слитые[-1][1] = max(слитые[-1][1], до)
        else:
            слитые.append([от, до])
    return [(round(от, 2), round(до, 2)) for от, до in слитые]


