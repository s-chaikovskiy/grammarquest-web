# -*- coding: utf-8 -*-
"""
Сборка ролика: мастер и две озвученные версии.

Мастер собирается из кадров, которые снял `записать.mjs`, и звука
приложения. Из мастера получаются ещё два файла — с дикторским текстом
по-русски и по-казахски. Картинка во всех трёх одна и та же, меняются
только звуковая дорожка и плашка с подписями.

    ../презентация/venv/bin/python собрать.py --мастер <папка кадров>
    ../презентация/venv/bin/python собрать.py            # обе озвученные версии
    ../презентация/venv/bin/python собрать.py ru         # одну версию
    ../презентация/venv/bin/python собрать.py --сцены    # разбор мастера

Нужен Python с Pillow (подписи рисуются им) и edge-tts из tools/.venv.

Что здесь важно и почему:

**Звук приложения — настоящий, а не придуманный.** Из headless Chrome звук
не снять, поэтому дорожка мастера собирается из тех же mp3, что лежат
в приложении, ровно в моменты из журнала записи. Щелчки и сигналы
«верно»/«неверно» синтезируются по параметрам из src/utils/sounds.ts —
те же частоты, длительности и громкости, в те же моменты, когда их
вызывает код приложения.

**Диктор не перебивает приложение.** Окна `ТИШИНА` считаются из журнала,
и сборка падает, если синтезированная реплика в них залезла хоть на сотую
долю секунды. После сборки дорожку диктора ещё и слушаем: в каждом окне
она обязана молчать. Это проверка, а не намерение.

**Подписи рисуются поверх плашки мастера.** Плашка непрозрачная, в мастере
на ней только название и адрес сайта, и подпись ложится ровно на неё.

**Текст подписи и текст диктора — один и тот же.** Подпись существует
для того, чтобы прочитать сказанное, а не для отдельного пересказа.

**Шрифт системный, не Golos.** Golos в проекте разложен на подмножества
(отдельно кириллица, отдельно казахские буквы), в одном файле нужного
набора нет, а слить их нельзя — это переменные шрифты. SF покрывает
и русский, и казахский, и кавычки, и цифры.
"""
