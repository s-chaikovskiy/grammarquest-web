def прогнать(аргументы, **кв):
    return subprocess.run(аргументы, check=True, capture_output=True, **кв)


def длительность(файл: pathlib.Path) -> float:
    вывод = прогнать(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                      "-of", "csv=p=0", str(файл)]).stdout
    return float(вывод.decode().strip())


def замерить(файл: pathlib.Path, цель_LUFS: float) -> dict:
    """Первый проход loudnorm: громкость и истинный пик входа."""
    замер = subprocess.run(
        ["ffmpeg", "-hide_banner", "-nostats", "-v", "info", "-i", str(файл),
         "-af", f"loudnorm=I={цель_LUFS}:TP={ПИК}:LRA=11:print_format=json",
         "-f", "null", "-"],
        capture_output=True, text=True).stderr
    кусок = re.search(r"\{[^{}]*\"input_i\"[^{}]*\}", замер, re.S)
    if not кусок:
        raise SystemExit(f"loudnorm не отдал замер для {файл.name}")
    return json.loads(кусок.group(0))


# ─────────────────────────── мастер ───────────────────────────

ЧАСТОТА = 48000


def _тон(дорожка: array.array, старт: float, частота: float, длит: float, громкость: float):
    """
    playTone из src/utils/sounds.ts: синус, громкость спадает по экспоненте
    от `громкость` до 0,01 за время звучания, потом осциллятор глохнет.
    """
    н0 = int(старт * ЧАСТОТА)
    for i in range(int(длит * ЧАСТОТА)):
        if н0 + i >= len(дорожка):
            break
        t = i / ЧАСТОТА
        усиление = громкость * (0.01 / громкость) ** (t / длит)
        дорожка[н0 + i] += усиление * math.sin(2 * math.pi * частота * t)


def щелчок(д, t):
    _тон(д, t, 1200, 0.03, 0.1)


def верно(д, t):
    for i, f in enumerate((523.25, 659.25, 783.99, 1046.50)):
        _тон(д, t + i * 0.08, f, 0.15, 0.2)


def неверно(д, t):
    _тон(д, t, 350, 0.25, 0.15)
    _тон(д, t + 0.15, 280, 0.35, 0.12)


def звуки_интерфейса(события: list[dict], конец: float) -> pathlib.Path:
    """
    Щелчки и сигналы проверки — там же, где их вызывает код:
      · любая кнопка, кроме «Тексеру», щёлкает (TaskInput, LessonScreen,
        LearnScreen, WelcomeScreen, LangSwitch);
      · вариант в задании с одним ответом проверяется через 350 мс;
      · «Тексеру» проверяет сразу и не щёлкает;
      · «Тыңдау» не щёлкает — звучит сама запись.
    Верно или нет — не из сценария, а из данных: ответ сравнивается
    с answers того задания, где есть такие варианты.
    """
    задания = [s for l in json.loads((ROOT / "src" / "data" / "lessons.json")
                                     .read_text(encoding="utf-8"))["lessons"]
               for s in l["steps"]]

    def задание_с(варианты):
        for s in задания:
            if set(варианты) <= set(s["task"]["options"]):
                return s["task"]
        raise SystemExit(f"нет задания с вариантами {варианты}")

    д = array.array("f", bytes(4 * int((конец + 1) * ЧАСТОТА)))
    отмечено: list[str] = []
    сигналов = []
    for с in события:
        if с["что"] != "нажатие":
            continue
        t, текст = с["t"], с["текст"]
        if текст == "Тексеру":
            task = задание_с(отмечено)
            ок = set(отмечено) == set(task["answers"])
            (верно if ок else неверно)(д, t)
            сигналов.append((t, "верно" if ок else "неверно", "+".join(отмечено)))
            отмечено = []
            continue
        щелчок(д, t)
        варианты_есть = any(текст in s["task"]["options"] for s in задания)
        if not варианты_есть:
            continue
        task = задание_с([текст])
        if task["kind"] == "multi":
            отмечено.append(текст)
        else:
            ок = текст in task["answers"]
            (верно if ок else неверно)(д, t + 0.35)
            сигналов.append((t + 0.35, "верно" if ок else "неверно", текст))

    for t, что, ответ in сигналов:
        print(f"  {t:6.2f}  сигнал «{что}»  ({ответ})")

    файл = ГОТОВОЕ / ".интерфейс.wav"
    пики = max(abs(x) for x in д)
    if пики >= 1.0:
        raise SystemExit(f"звуки интерфейса перегружены: пик {пики:.2f}")
    with wave.open(str(файл), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(ЧАСТОТА)
        w.writeframes(array.array("h", (int(x * 32767) for x in д)).tobytes())
    return файл


def собрать_мастер(кадры: pathlib.Path):
    журнал = json.loads((кадры / "журнал.json").read_text(encoding="utf-8"))
    if журнал["кадр"] != [КАДР[0], ПЛАШКА_Y]:
        raise SystemExit(f"кадр записи {журнал['кадр']}, а сборка ждёт {[КАДР[0], ПЛАШКА_Y]}")
    ГОТОВОЕ.mkdir(exist_ok=True)
    события = журнал["события"]
    конец = next(с["t"] for с in события if с["что"] == "конец")
    список = журнал["кадры"]
    print(f"\n=== мастер · {len(список)} кадров, {конец:.2f} с ===")

    # 1. Картинка: каждый снимок висит до следующего. Скорость съёмки
    # плавает, поэтому длительности из журнала, а не «по N кадров в секунду».
    склейка = ГОТОВОЕ / ".кадры.txt"
    строки = ["ffconcat version 1.0"]
    for i, к in enumerate(список):
        следующий = список[i + 1]["t"] if i + 1 < len(список) else конец
        строки += [f"file '{кадры / к['имя']}'", f"duration {max(следующий - к['t'], 0.001):.3f}"]
    строки.append(f"file '{кадры / список[-1]['имя']}'")
    склейка.write_text("\n".join(строки) + "\n", encoding="utf-8")

    плашка = ГОТОВОЕ / ".плашка-мастера.png"
    нарисовать_подпись(НАДПИСЬ_МАСТЕРА, плашка)

    # 2. Звук: записи озвучки в моменты из журнала плюс звуки интерфейса.
    интерфейс = звуки_интерфейса(события, конец)
    записи = [с for с in события if с["что"] == "звук"]
    вход = ["-i", str(интерфейс)]
    цепь = ["[0:a]aresample=48000[и]"]
    звенья = ["[и]"]
    for k, с in enumerate(записи, start=1):
        вход += ["-i", str(ROOT / с["файл"])]
        мс = int(round(с["t"] * 1000))
        цепь.append(f"[{k}:a]aresample=48000,adelay={мс}|{мс}[з{k}]")
        звенья.append(f"[з{k}]")
        print(f"  {с['t']:6.2f}  запись «{с['текст']}»  {с['длительность']:.2f} с")
    цепь.append("".join(звенья) + f"amix=inputs={len(звенья)}:normalize=0,"
                                  f"apad,atrim=0:{конец:.3f}[звук]")
    сырой = ГОТОВОЕ / ".звук-мастера.wav"
    прогнать(["ffmpeg", "-v", "error", "-y", *вход, "-filter_complex", ";".join(цепь),
              "-map", "[звук]", "-c:a", "pcm_s16le", "-ac", "1", str(сырой)])

    # Громкость — одним линейным усилением: записи в приложении тихие
    # (−21…−24 LUFS), но сжимать речь нельзя. Поднимаем до −16 LUFS или
    # до потолка по пику — что наступит раньше.
    з = замерить(сырой, ГРОМКОСТЬ_РОЛИКА)
    усиление = min(ГРОМКОСТЬ_РОЛИКА - float(з["input_i"]), ПИК - float(з["input_tp"]))
    print(f"  звук приложения: {з['input_i']} LUFS, пик {з['input_tp']} dBTP → "
          f"усиление {усиление:+.1f} дБ")

    # 3. Сведение.
    прогнать(["ffmpeg", "-v", "error", "-y", "-f", "concat", "-safe", "0", "-i", str(склейка),
              "-i", str(плашка), "-i", str(сырой),
              "-filter_complex",
              f"[0:v]fps={FPS},pad={КАДР[0]}:{КАДР[1]}:0:0:color=0x3A3F46[п];"
              f"[п][1:v]overlay=0:{ПЛАШКА_Y},format=yuv420p[v];"
              f"[2:a]volume={усиление:.2f}dB[a]",
              "-map", "[v]", "-map", "[a]", "-t", f"{конец:.3f}",
              "-c:v", "libx264", "-crf", "18", "-preset", "slow",
              "-c:a", "aac", "-b:a", "128k", "-ac", "1",
              "-movflags", "+faststart", str(МАСТЕР)])
    for f in (склейка, плашка, интерфейс, сырой):
        f.unlink()

    # Журнал — рядом с мастером: по нему считаются окна тишины для диктора.
    ЖУРНАЛ.write_text(json.dumps(журнал, ensure_ascii=False, indent=1), encoding="utf-8")

    д = длительность(МАСТЕР)
    if abs(д - конец) > 0.1:
        raise SystemExit(f"длительность мастера {д:.2f} вместо {конец:.2f}")
    print(f"  собрано: {МАСТЕР.name}  {МАСТЕР.stat().st_size / 1e6:.2f} МБ, {д:.2f} с")


# ─────────────────────────── разбор мастера ───────────────────────────

def сцены_мастера() -> list[dict]:
    """
    Где в мастере меняется картинка. Смена видна как скачок яркости
    уменьшенного кадра. Короткие всплески (меньше 0,6 с) — это переходы
    между экранами, они склеиваются с предыдущей сценой.
    """
    сырое = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(МАСТЕР),
         "-vf", f"crop={КАДР[0]}:{ПЛАШКА_Y}:0:0,scale=78:159",
         "-pix_fmt", "gray", "-f", "rawvideo", "-"],
        check=True, capture_output=True).stdout

    размер = 78 * 159
    n = len(сырое) // размер
    кадры = [array.array("B", сырое[i * размер:(i + 1) * размер]) for i in range(n)]
    fps = n / длительность(МАСТЕР)

    def отличие(a, b):
        return sum(abs(x - y) for x, y in zip(a, b)) / len(a)

    смена = [0] + [i for i in range(1, n) if отличие(кадры[i], кадры[i - 1]) > 2.0]
    блоки = []
    for j, i in enumerate(смена):
        конец = смена[j + 1] if j + 1 < len(смена) else n
        if (конец - i) / fps < 0.6 and блоки:
            continue
        блоки.append(i)
    итог = []
    for j, i in enumerate(блоки):
        конец = блоки[j + 1] if j + 1 < len(блоки) else n
        итог.append({"от": round(i / fps, 2), "до": round(конец / fps, 2)})
    return итог


# ─────────────────────────── синтез речи ───────────────────────────

# Синтез приклеивает к каждой реплике около 1,2 секунды тишины — по полсекунды
# с каждого края. На минутном ролике это пятнадцать секунд пустоты, из-за
# которых короткие реплики не влезали в свои окна. Подрезаем сразу после
# синтеза, чтобы дальше везде считалась настоящая длительность речи.
ПОДРЕЗКА = ("silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.02,"
            "areverse,"
            "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.02,"
            "areverse")

ГРОМКОСТЬ_ДИКТОРА = -16.0    # LUFS, к ней приводится каждая реплика по отдельности
ГРОМКОСТЬ_РОЛИКА = -16.0     # LUFS, обычная величина для короткого ролика в вебе
ПИК = -1.5                   # dBTP


def озвучить(текст: str, голос: str) -> pathlib.Path:
    """Синтез с кэшем: одинаковый текст одним голосом не переозвучивается."""
    ОЗВУЧКА.mkdir(exist_ok=True)
    ключ = hashlib.sha256(f"{голос}|{текст}".encode()).hexdigest()[:12]
    сырой = ОЗВУЧКА / f"{ключ}-сырой.mp3"
    файл = ОЗВУЧКА / f"{ключ}.mp3"
    if not файл.exists():
        if not сырой.exists():
            прогнать([str(EDGE), "--voice", голос, "--text", текст,
                      "--write-media", str(сырой)])
        подрезанный = ОЗВУЧКА / f"{ключ}-подрезанный.wav"
        прогнать(["ffmpeg", "-v", "error", "-y", "-i", str(сырой),
                  "-af", ПОДРЕЗКА, str(подрезанный)])
        выровнять(подрезанный, файл)
        подрезанный.unlink()
    return файл


def выровнять(вход: pathlib.Path, выход: pathlib.Path,
              цель_LUFS: float = ГРОМКОСТЬ_ДИКТОРА, копировать_видео: bool = False):
    """
    Громкость в два прохода: сначала замер, потом приведение по замеру.

    Однопроходный loudnorm промахивается — русская и казахская версии
    расходились на полтора LUFS, и один и тот же ролик звучал по-разному
    в зависимости от языка. Диктор — не музыка, разброс тут слышен сразу.
    """
    цель = (f"loudnorm=I={цель_LUFS}:TP={ПИК}:LRA=11")
    д = замерить(вход, цель_LUFS)
    хвост = (["-c:v", "copy", "-c:a", "aac", "-b:a", "128k", "-ac", "1",
              "-movflags", "+faststart"] if копировать_видео else ["-ar", "48000"])
    прогнать(["ffmpeg", "-v", "error", "-y", "-i", str(вход), "-af",
              f"{цель}:measured_I={д['input_i']}:measured_TP={д['input_tp']}"
              f":measured_LRA={д['input_lra']}:measured_thresh={д['input_thresh']}"
              f":offset={д['target_offset']}:linear=true",
              *хвост, str(выход)])


# ─────────────────────────── подписи ───────────────────────────

def разложить(текст: str, шрифт, ширина: int) -> list[str]:
    """Перенос по словам. Больше двух строк плашка не вмещает."""
    слова = текст.split()
    строки, текущая = [], ""
    for слово in слова:
        проба = f"{текущая} {слово}".strip()
        if шрифт.getlength(проба) <= ширина or not текущая:
            текущая = проба
        else:
            строки.append(текущая)
            текущая = слово
    строки.append(текущая)
    return строки


def нарисовать_подпись(текст: str, файл: pathlib.Path):
    from PIL import Image, ImageDraw, ImageFont

    ширина = КАДР[0] - 2 * ПОЛЯ
    кегль = 30
    while кегль > 16:
        шрифт = ImageFont.truetype(ШРИФТ, кегль)
        шрифт.set_variation_by_axes(ОСИ)
        строки = разложить(текст, шрифт, ширина)
        if len(строки) <= МАКС_СТРОК:
            break
        кегль -= 1
    else:
        raise SystemExit(f"подпись не влезает в две строки: {текст}")

    им = Image.new("RGB", (КАДР[0], ПЛАШКА_H), ПЛАШКА_ЦВЕТ)
    рис = ImageDraw.Draw(им)
    шаг = кегль + 8
    верх = (ПЛАШКА_H - шаг * len(строки)) / 2 + шаг / 2
    for i, строка in enumerate(строки):
        рис.text((КАДР[0] / 2, верх + i * шаг), строка,
                 font=шрифт, fill=(255, 255, 255), anchor="mm")
    им.save(файл)
    return кегль, len(строки)


# ─────────────────────────── проверки ───────────────────────────

def проверить_тишину(реплики: list[dict]):
    """Ни одна реплика диктора не смеет попасть в окно приложения."""
    for от, до in Т.ТИШИНА:
        for р in реплики:
            if р["конец"] > от and р["старт"] < до:
                raise SystemExit(
                    f"диктор перебивает приложение: «{р['текст'][:40]}…» "
                    f"звучит {р['старт']:.2f}–{р['конец']:.2f}, "
                    f"а приложение говорит {от:.2f}–{до:.2f}")


def проверить_дорожку(дорожка: pathlib.Path):
    """
    Слушаем собранную дорожку диктора: в каждом окне, где говорит приложение,
    она обязана быть тишиной. Ищем не паузы, а наоборот — звук, и ругаемся,
    если он нашёлся там, где его быть не должно.
    """
    вывод = subprocess.run(
        ["ffmpeg", "-v", "info", "-i", str(дорожка),
         "-af", "silencedetect=noise=-50dB:d=0.05", "-f", "null", "-"],
        capture_output=True, text=True).stderr
    паузы = []
    начало = None
    for м in re.finditer(r"silence_(start|end): (-?[\d.]+)", вывод):
        if м.group(1) == "start":
            начало = float(м.group(2))
        elif начало is not None:
            паузы.append((начало, float(м.group(2))))
            начало = None
    if начало is not None:
        паузы.append((начало, длительность(дорожка)))

    for от, до in Т.ТИШИНА:
        накрыто = any(п <= от + 0.001 and к >= до - 0.001 for п, к in паузы)
        if not накрыто:
            raise SystemExit(
                f"дорожка диктора не молчит в окне {от:.2f}–{до:.2f}: "
                f"паузы {[(round(a,2), round(b,2)) for a, b in паузы]}")
        print(f"  ✓ дорожка диктора молчит с {от:.2f} по {до:.2f} — "
              f"в это окно говорит только приложение")


def проверить_окна(реплики: list[dict]):
    """Реплика обязана уложиться в своё окно и не наехать на следующую."""
    плохо = 0
    for i, р in enumerate(реплики):
        if р["конец"] > р["до"] + 0.01:
            плохо += 1
            print(f"  ✗ не влезает на {р['конец'] - р['до']:.2f} с: «{р['текст']}»")
        if i + 1 < len(реплики) and р["конец"] > реплики[i + 1]["старт"]:
            плохо += 1
            print(f"  ✗ наезжает на следующую: «{р['текст']}»")
    return плохо


def проверить_подписи():
    """Подписи идут встык и по порядку: две сразу на плашке не висят."""
    for а, б in zip(Т.СТРОКИ, Т.СТРОКИ[1:]):
        if not а["от"] < а["до"] <= б["от"]:
            raise SystemExit(f"подписи наезжают: «{а['ru']}» и «{б['ru']}»")
    окна_приложения = [(с["от"], с["до"]) for с in Т.СТРОКИ if с.get("диктор") is False]
    if окна_приложения != list(Т.ТИШИНА):
        raise SystemExit(f"подписи «говорит приложение» {окна_приложения} "
                         f"не совпадают с окнами тишины {Т.ТИШИНА}")


# ─────────────────────────── сборка ───────────────────────────

def срт(язык: str) -> str:
    def метка(t):
        ч, ост = divmod(t, 3600)
        м, с = divmod(ост, 60)
        return f"{int(ч):02d}:{int(м):02d}:{int(с):02d},{int(round((с % 1) * 1000)):03d}"

    куски = []
    for i, строка in enumerate(Т.СТРОКИ, 1):
        куски.append(f"{i}\n{метка(строка['от'])} --> {метка(строка['до'])}\n{строка[язык]}\n")
    return "\n".join(куски)


def собрать(язык: str):
    ГОТОВОЕ.mkdir(exist_ok=True)
    подписи_дир = ГОТОВОЕ / f"подписи-{язык}"
    подписи_дир.mkdir(exist_ok=True)
    for старая in подписи_дир.glob("*.png"):
        старая.unlink()

    print(f"\n=== {язык} · {Т.ГОЛОС[язык]} ===")
    проверить_подписи()

    # 1. Синтез и замер.
    реплики = []
    картинки = []
    for i, строка in enumerate(Т.СТРОКИ):
        текст = строка[язык]
        png = подписи_дир / f"{i:02d}.png"
        кегль, строк = нарисовать_подпись(текст, png)
        картинки.append((png, строка["от"], строка["до"]))

        if строка.get("диктор") is False:
            print(f"  {строка['от']:6.2f}  [говорит приложение]  {текст[:46]}")
            continue

        мп3 = озвучить(текст, Т.ГОЛОС[язык])
        д = длительность(мп3)
        старт = строка["от"] + (0.35 if i == 0 else 0.15)
        реплики.append({"файл": мп3, "старт": старт, "конец": старт + д,
                        "до": строка["до"], "текст": текст})
        запас = строка["до"] - (старт + д)
        знак = "✓" if запас >= -0.01 else "✗"
        print(f"  {знак} {старт:6.2f} +{д:5.2f} с  запас {запас:+5.2f}  "
              f"{кегль}pt/{строк}стр  {текст[:44]}")

    # 2. Проверки до сборки: пересобирать ролик из-за наложения — дорого.
    проверить_тишину(реплики)
    if проверить_окна(реплики):
        raise SystemExit("реплики не укладываются в окна — сократите текст")

    # 3. Видео: подписи поверх плашки мастера.
    вход = ["-i", str(МАСТЕР)]
    цепь = []
    метка = "0:v"
    for n, (png, от, до) in enumerate(картинки, start=1):
        вход += ["-i", str(png)]
        новая = f"v{n}"
        цепь.append(f"[{метка}][{n}:v]overlay=0:{ПЛАШКА_Y}:"
                    f"enable='between(t,{от},{до})'[{новая}]")
        метка = новая

    # 4. Звук: дорожка диктора и звук приложения.
    первый_звук = len(картинки) + 1
    звенья = []
    for k, р in enumerate(реплики):
        вход += ["-i", str(р["файл"])]
        мс = int(round(р["старт"] * 1000))
        цепь.append(f"[{первый_звук + k}:a]aresample=48000,adelay={мс}|{мс}[д{k}]")
        звенья.append(f"[д{k}]")
    # asplit: дорожка диктора нужна дважды — в общую смесь и отдельным
    # файлом для проверки. Выход фильтра можно взять только один раз.
    цепь.append("".join(звенья) + f"amix=inputs={len(звенья)}:normalize=0,"
                                  "asplit=2[диктор][диктор-копия]")
    # Звук мастера уже приведён к той же громкости, что и реплики диктора,
    # поэтому поднимать его здесь не нужно: приложение и диктор звучат
    # на равных, а говорят они в разное время.
    цепь.append("[0:a]aresample=48000[приложение]")
    цепь.append("[диктор][приложение]amix=inputs=2:normalize=0,"
                # level=false обязателен. По умолчанию alimiter не срезает
                # пики, а подтягивает к порогу всю смесь — то есть работает
                # автоусилением. С ним пик держался у −0,4 дБ, что бы я
                # ни ставил в limit, и громкость дорожек переставала значить
                # хоть что-нибудь.
                "alimiter=limit=0.89:level=false[звук]")

    выход = ГОТОВОЕ / Т.ИМЕНА[язык]
    черновик = ГОТОВОЕ / f".черновик-{язык}.mp4"
    # Дорожку диктора выводим отдельным файлом: по ней потом видно, молчал ли
    # он в окнах приложения. Проверка по расчёту длительностей уже была выше,
    # но она верит арифметике, а эта слушает то, что действительно собралось.
    только_диктор = ГОТОВОЕ / f"дорожка-диктора-{язык}.wav"
    прогнать(["ffmpeg", "-v", "error", "-y", *вход,
              "-filter_complex", ";".join(цепь),
              "-map", f"[{метка}]", "-map", "[звук]",
              "-c:v", "libx264", "-crf", "18", "-preset", "slow", "-pix_fmt", "yuv420p",
              "-c:a", "aac", "-b:a", "128k", "-ac", "1",
              "-movflags", "+faststart", str(черновик),
              "-map", "[диктор-копия]", "-c:a", "pcm_s16le", str(только_диктор)])
    проверить_дорожку(только_диктор)

    # Последним шагом приводим смесь целиком. Без него ролики расходились
    # по громкости на 1,2 LUFS: в казахской версии реплики короче, речи
    # в минуте меньше, и весь ролик выходил тише при тех же дорожках.
    # Картинку не трогаем — она перекладывается без перекодирования.
    выровнять(черновик, выход, ГРОМКОСТЬ_РОЛИКА, копировать_видео=True)
    черновик.unlink()

    (ГОТОВОЕ / f"{выход.stem}.srt").write_text(срт(язык), encoding="utf-8")

    # 5. Проверка готового файла.
    д = длительность(выход)
    эталон = длительность(МАСТЕР)
    if abs(д - эталон) > 0.1:
        raise SystemExit(f"длительность уехала: {д:.2f} вместо {эталон:.2f}")
    пик = subprocess.run(["ffmpeg", "-v", "info", "-i", str(выход),
                          "-af", "volumedetect", "-f", "null", "-"],
                         capture_output=True, text=True).stderr
    м = re.search(r"max_volume:\s*(-?[\d.]+)", пик)
    print(f"  собрано: {выход.name}  {выход.stat().st_size / 1e6:.2f} МБ, "
          f"{д:.2f} с, пик {м.group(1) if м else '?'} дБ")
    return выход


def main():
    аргументы = sys.argv[1:]
    if "--мастер" in аргументы:
        собрать_мастер(pathlib.Path(аргументы[аргументы.index("--мастер") + 1]).resolve())
        return
    if "--сцены" in аргументы:
        for с in сцены_мастера():
            print(f"  {с['от']:6.2f} – {с['до']:6.2f} с")
        return
    языки = [а for а in аргументы if а in Т.ГОЛОС] or list(Т.ГОЛОС)
    for язык in языки:
        собрать(язык)


if __name__ == "__main__":
    main()
