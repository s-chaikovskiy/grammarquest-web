def проверить_памятку():
    """
    Памятку открывают «Блокнотом» на школьном компьютере. Без BOM он покажет
    кракозябры, без переводов строк Windows — слепит текст в одну строку.
    Проверка появилась после того, как правка через обычную запись файла
    молча заменила все CRLF на LF.
    """
    d = (ROOT / "комплект" / "ЧИТАТЬ-ПЕРВЫМ.txt").read_bytes()
    беды = []
    if d[:3] != b"\xef\xbb\xbf":
        беды.append("нет BOM")
    одиночных = d.count(b"\n") - d.count(b"\r\n")
    if одиночных:
        беды.append(f"{одиночных} переводов строк не по-виндовому")
    if беды:
        raise SystemExit("ЧИТАТЬ-ПЕРВЫМ.txt: " + ", ".join(беды))


def main():
    проверить_памятку()
    if OUT.exists():
        shutil.rmtree(OUT)
    нет = []
    for источник, назначение in ФАЙЛЫ:
        src = ROOT / источник
        if not src.exists():
            нет.append(источник)
            continue
        dst = OUT / назначение
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)

    if нет:
        print("НЕ ХВАТАЕТ:")
        for f in нет:
            print("  ✗", f)

    # «Блокнот» на школьном ПК без BOM показывает кириллицу кракозябрами,
    # а без CRLF слепляет весь текст в одну строку.
    памятка = OUT / "ЧИТАТЬ-ПЕРВЫМ.txt"
    if памятка.exists():
        текст = памятка.read_text(encoding="utf-8").lstrip("\ufeff")
        памятка.write_bytes(
            ("\ufeff" + текст.replace("\r\n", "\n").replace("\n", "\r\n")).encode("utf-8"))

    ARCHIVE.unlink(missing_ok=True)
    with zipfile.ZipFile(ARCHIVE, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for f in sorted(OUT.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(OUT.parent))

    print(f"\nСобрано: {ARCHIVE.name}  ({ARCHIVE.stat().st_size / 1048576:.1f} МБ)")
    for f in sorted(OUT.rglob("*")):
        if f.is_file():
            print(f"  {f.relative_to(OUT)}  ·  {f.stat().st_size / 1048576:.2f} МБ")


if __name__ == "__main__":
    main()
