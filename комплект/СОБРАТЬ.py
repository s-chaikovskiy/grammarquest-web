# Папки копируются целиком. Шрифты нужны, чтобы .pptx открылся тем же,
# чем собран: без них PowerPoint подставит свой и вёрстка поедет.
ПАПКИ = [
    ("презентация/шрифты", "2-Презентация/шрифты"),
]


def проверить_тексты():
    """
    Текстовые файлы открывают «Блокнотом» на школьном компьютере. Без BOM
    он покажет кракозябры, без переводов строк Windows — слепит текст
    в одну строку. Проверка появилась после того, как правка через обычную
    запись файла молча заменила все CRLF на LF.
    """
    беды = []
    for источник, _ in ФАЙЛЫ:
        if not источник.endswith(".txt"):
            continue
        файл = ROOT / источник
        if not файл.exists():
            continue
        d = файл.read_bytes()
        if d[:3] != b"\xef\xbb\xbf":
            беды.append(f"{файл.name}: нет BOM")
        одиночных = d.count(b"\n") - d.count(b"\r\n")
        if одиночных:
            беды.append(f"{файл.name}: {одиночных} переводов строк не по-виндовому")
    if беды:
        raise SystemExit("\n".join("  ✗ " + б for б in беды))


def main():
    # Памятку докладчику пересобираем из заметок к слайдам: она не должна
    # разойтись с колодой, а разойдётся молча.
    subprocess.run([sys.executable, str(ROOT / "комплект" / "памятка-докладчику.py")],
                   check=True)
    проверить_тексты()
    if OUT.exists():
        shutil.rmtree(OUT)
    нет = []
    for источник, назначение in ФАЙЛЫ:
        src = ROOT / источник
        if not src.exists():
            нет.append(источник)
            continue
        dst = OUT / назначение
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)

    for источник, назначение in ПАПКИ:
        src = ROOT / источник
        if not src.is_dir():
            нет.append(источник + "/")
            continue
        shutil.copytree(src, OUT / назначение)

    if нет:
        print("НЕ ХВАТАЕТ:")
        for f in нет:
            print("  ✗", f)

    ARCHIVE.unlink(missing_ok=True)
    with zipfile.ZipFile(ARCHIVE, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for f in sorted(OUT.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(OUT.parent))

    print(f"\nСобрано: {ARCHIVE.name}  ({ARCHIVE.stat().st_size / 1048576:.1f} МБ)")
    for f in sorted(OUT.rglob("*")):
        if f.is_file():
            print(f"  {f.relative_to(OUT)}  ·  {f.stat().st_size / 1048576:.2f} МБ")


if __name__ == "__main__":
    main()
