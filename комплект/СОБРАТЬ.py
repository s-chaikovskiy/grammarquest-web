def собрать_язык(язык: str) -> pathlib.Path:
    папки = НАЗВАНИЯ_ПАПОК[язык]
    корень = ВЫХОД / ИМЯ_АРХИВА[язык]
    if корень.exists():
        shutil.rmtree(корень)
    корень.mkdir(parents=True)

    нет = []
    for источник, назначение in ОБЩЕЕ + ПО_ЯЗЫКАМ[язык]:
        src = ROOT / источник
        if not src.exists():
            нет.append(источник)
            continue
        dst = корень / назначение.format(**папки)
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)

    for источник, назначение in ПАПКИ[язык]:
        src = ROOT / источник
        if not src.is_dir():
            нет.append(источник + "/")
            continue
        shutil.copytree(src, корень / назначение.format(**папки))

    # Письмо и памятка о комплекте — на языке архива, пишутся сразу сюда.
    Т.собрать(язык, корень)

    if нет:
        print("НЕ ХВАТАЕТ:")
        for f in нет:
            print("  ✗", f)

    архив = ВЫХОД / f"{ИМЯ_АРХИВА[язык]}.zip"
    архив.unlink(missing_ok=True)
    with zipfile.ZipFile(архив, "w", zipfile.ZIP_DEFLATED) as z:
        for файл in sorted(корень.rglob("*")):
            if файл.is_file():
                z.write(файл, файл.relative_to(ВЫХОД))
    return архив


def проверить_тексты(корень: pathlib.Path):
    """Файлы открывают «Блокнотом»: без BOM кракозябры, без CRLF одна строка."""
    беды = []
    for файл in sorted(корень.rglob("*.txt")):
        # Лицензию шрифта не трогаем: она чужая и читателю не адресована.
        if файл.name.startswith("OFL"):
            continue
        d = файл.read_bytes()
        if d[:3] != b"\xef\xbb\xbf":
            беды.append(f"{файл.name}: нет BOM")
        одиночных = d.count(b"\n") - d.count(b"\r\n")
        if одиночных:
            беды.append(f"{файл.name}: {одиночных} переводов строк не по-виндовому")
    if беды:
        raise SystemExit("\n".join("  ✗ " + б for б in беды))


# Где в письмах какие числа и что им позволено значить. У «тем» и «заданий»
# три верных значения: всего, у учителя и у ассистента, — все три стоят
# в письмах. Остальное — одно значение, и оно считается из самих файлов.
ЧИСЛА = {
    "тем": (r"(\d+)\s+тақырып", r"(\d+)\s+тем\b"),
    "заданий": (r"(\d+)\s+тапсырма", r"(\d+)\s+задани"),
    "записей": (r"(\d+)\s+(?:дыбыс\s+)?жазба", r"(\d+)\s+запис"),
    "страниц": (r"(\d+)\s+бет\b", r"(\d+)\s+стр\b"),
    "слайдов": (r"(\d+)\s+слайд",),
    "секунд": (r"(\d+)\s+секунд(?![ыа]|тар)",),
    "исправлений": (r"(\d+)\s+түзету", r"(\d+)\s+исправлени"),
}
СЛЕДЫ_ПРОШЛОЙ = ["2.0.0", "Тілашар-2.0", "623", "225", "русскими буквами",
                 "орыс әріптерімен", "Сабақтар жолы", "Дорожка уроков"]


def факты() -> dict[str, set[int]]:
    """Каждое число — из первоисточника: данных, PDF, колоды, мастера ролика."""
    import json
    import re
    данные = json.loads((ROOT / "src/data/lessons.json").read_text(encoding="utf-8"))["lessons"]
    учитель = [l for l in данные if l["author"] == "учитель"]
    прочие = [l for l in данные if l["author"] != "учитель"]
    шагов = lambda ls: sum(len(l["steps"]) for l in ls)  # noqa: E731
    записей = len(json.loads((ROOT / "src/data/audio-index.json").read_text(encoding="utf-8"))["available"])
    страниц = {len(re.findall(rb"/Type\s*/Page[^s]", f.read_bytes()))
               for f in (ROOT / "документы").glob("Тілашар – *.pdf")}
    слайдов = {len([n for n in zipfile.ZipFile(f).namelist()
                    if re.fullmatch(r"ppt/slides/slide\d+\.xml", n)])
               for f in (ROOT / "презентация").glob("Тілашар-*.pptx")}
    секунд = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                                   "-of", "csv=p=0", str(ROOT / "видео/мастер.mp4")],
                                  capture_output=True, text=True, check=True).stdout)
    sys.path.insert(0, str(ROOT / "tools" / "content"))
    from сабақтар import ПРАВКИ
    return {
        "тем": {len(данные), len(учитель), len(прочие)},
        "заданий": {шагов(данные), шагов(учитель), шагов(прочие)},
        "записей": {записей},
        "страниц": страниц,
        "слайдов": слайдов,
        "секунд": {int(секунд)},
        "исправлений": {len(ПРАВКИ)},
    }


def проверить_числа(корень: pathlib.Path, язык: str, ф: dict[str, set[int]]):
    """Письмо, где число разошлось с файлами, хуже письма без чисел."""
    import re
    беды = []
    for файл in (корень / имя for имя in Т.ИМЕНА[язык].values()):
        текст = файл.read_text(encoding="utf-8-sig")
        for что, шаблоны in ЧИСЛА.items():
            for шаблон in шаблоны:
                for n in {int(м) for м in re.findall(шаблон, текст, re.I)}:
                    if n not in ф[что]:
                        беды.append(f"{файл.name}: «{n} {что}», а по данным {sorted(ф[что])}")
        for след in СЛЕДЫ_ПРОШЛОЙ:
            if след in текст:
                беды.append(f"{файл.name}: след прошлой версии «{след}»")
    # Памятку докладчику собирают заметки колоды, но шапка и концовка у неё
    # свои — концовка 2.0 про «русские буквы» пережила переделку колоды.
    # Числа в ней не сверяем: в заметках есть секунды на показ и прочее.
    памятка = корень / "5-Ученику" / "ПАМЯТКА-ДОКЛАДЧИКА.txt"
    if памятка.exists():
        текст = памятка.read_text(encoding="utf-8-sig")
        for след in СЛЕДЫ_ПРОШЛОЙ:
            if след in текст:
                беды.append(f"{памятка.name}: след прошлой версии «{след}»")
    if беды:
        raise SystemExit("\n".join("  ✗ " + б for б in беды))
    print(f"  ✓ числа в письмах {корень.name} сходятся с файлами")


def main():
    # Памятку докладчику пересобираем из заметок к слайдам: она не должна
    # разойтись с колодой, а разойдётся молча.
    subprocess.run([sys.executable, str(ROOT / "комплект" / "памятка-докладчику.py")],
                   check=True)
    ВЫХОД.mkdir(exist_ok=True)
    ф = факты()
    for язык in ("kk", "ru"):
        архив = собрать_язык(язык)
        проверить_тексты(ВЫХОД / ИМЯ_АРХИВА[язык])
        проверить_числа(ВЫХОД / ИМЯ_АРХИВА[язык], язык, ф)
        размер = архив.stat().st_size / 1e6
        файлов = sum(1 for f in (ВЫХОД / ИМЯ_АРХИВА[язык]).rglob("*") if f.is_file())
        print(f"\n{архив.name}  ({размер:.1f} МБ, {файлов} файлов)")
        for файл in sorted((ВЫХОД / ИМЯ_АРХИВА[язык]).rglob("*")):
            if файл.is_file() and "шрифты" not in файл.parts:
                отн = файл.relative_to(ВЫХОД / ИМЯ_АРХИВА[язык])
                print(f"  {отн}  ·  {файл.stat().st_size / 1e6:.2f} МБ")
        print("  2-Презентация/шрифты/  ·  8 файлов, ставятся перед открытием .pptx")


if __name__ == "__main__":
    main()
