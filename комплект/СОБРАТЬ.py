# -*- coding: utf-8 -*-
"""
Сборка комплекта для учителя.

Состав повторяет то, что прислала она сама: документы, видео и файл
приложения. Добавлена презентация — её в прошлом комплекте не было,
но на защите она нужна.

Скрипт ничего не сочиняет: он берёт уже собранные файлы и раскладывает
их по папкам с понятными названиями. Если файла нет — говорит об этом
и не делает вид, что комплект полный.

    python3 комплект/СОБРАТЬ.py
"""
import pathlib
import shutil
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "комплект" / "Тілашар-2.0"
ARCHIVE = ROOT / "комплект" / "Тілашар-2.0.zip"

ФАЙЛЫ = [
    # (откуда, куда внутри комплекта)
    ("документы/Тілашар – техникалық сипаттама.docx", "1-Құжаттар/Тілашар – техникалық сипаттама.docx"),
    ("документы/Тілашар – техникалық сипаттама.pdf",  "1-Құжаттар/Тілашар – техникалық сипаттама.pdf"),
    ("документы/Тілашар – пайдаланушы нұсқаулығы.docx", "1-Құжаттар/Тілашар – пайдаланушы нұсқаулығы.docx"),
    ("документы/Тілашар – пайдаланушы нұсқаулығы.pdf",  "1-Құжаттар/Тілашар – пайдаланушы нұсқаулығы.pdf"),
    ("презентация/Тілашар-қорғау.pdf",  "2-Презентация/Тілашар-қорғау (қазақша).pdf"),
    ("презентация/Тілашар-қорғау.pptx", "2-Презентация/Тілашар-қорғау (қазақша).pptx"),
    ("презентация/Тілашар-защита.pdf",  "2-Презентация/Тілашар-защита (по-русски).pdf"),
    ("презентация/Тілашар-защита.pptx", "2-Презентация/Тілашар-защита (по-русски).pptx"),
    ("комплект/видео/Тілашар — как работает приложение.mp4", "3-Видео/Тілашар — қосымша қалай жұмыс істейді.mp4"),
    ("комплект/apk/Tilashar.apk", "4-Қосымша/Tilashar.apk"),
    ("комплект/ЧИТАТЬ-ПЕРВЫМ.txt", "ЧИТАТЬ-ПЕРВЫМ.txt"),
]


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    нет = []
    for источник, назначение in ФАЙЛЫ:
        src = ROOT / источник
        if not src.exists():
            нет.append(источник)
            continue
        dst = OUT / назначение
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)

    if нет:
        print("НЕ ХВАТАЕТ:")
        for f in нет:
            print("  ✗", f)

    # «Блокнот» на школьном ПК без BOM показывает кириллицу кракозябрами,
    # а без CRLF слепляет весь текст в одну строку.
    памятка = OUT / "ЧИТАТЬ-ПЕРВЫМ.txt"
    if памятка.exists():
        текст = памятка.read_text(encoding="utf-8").lstrip("\ufeff")
        памятка.write_bytes(
            ("\ufeff" + текст.replace("\r\n", "\n").replace("\n", "\r\n")).encode("utf-8"))

    ARCHIVE.unlink(missing_ok=True)
    with zipfile.ZipFile(ARCHIVE, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for f in sorted(OUT.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(OUT.parent))

    print(f"\nСобрано: {ARCHIVE.name}  ({ARCHIVE.stat().st_size / 1048576:.1f} МБ)")
    for f in sorted(OUT.rglob("*")):
        if f.is_file():
            print(f"  {f.relative_to(OUT)}  ·  {f.stat().st_size / 1048576:.2f} МБ")


if __name__ == "__main__":
    main()
