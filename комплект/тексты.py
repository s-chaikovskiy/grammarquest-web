def записать(текст: str, файл: pathlib.Path):
    """С BOM и переводами строк Windows: файлы открывают «Блокнотом»."""
    тело = текст.replace("\r\n", "\n").replace("\n", "\r\n")
    файл.parent.mkdir(parents=True, exist_ok=True)
    файл.write_bytes(b"\xef\xbb\xbf" + тело.encode("utf-8"))


def собрать(язык: str, куда: pathlib.Path) -> dict[str, pathlib.Path]:
    вышло = {}
    for вид, текст in (("письмо", ПИСЬМО[язык]), ("памятка", ПАМЯТКА[язык])):
        файл = куда / ИМЕНА[язык][вид]
        записать(ШАПКА[язык] + "\n" + текст + "\n", файл)
        вышло[вид] = файл
    return вышло


