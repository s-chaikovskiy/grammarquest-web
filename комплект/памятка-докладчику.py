# -*- coding: utf-8 -*-
"""
Памятка докладчику — из заметок к слайдам, а не отдельным текстом.

Заметки уже написаны и лежат внутри `.pptx`. Переписать их руками в третий
файл значило бы завести копию, которая назавтра разойдётся с колодой:
в проекте это уже случалось с числами. Поэтому памятка собирается
из презентации — правится колода, памятка следует за ней.

Формат — .txt с BOM и переводами строк Windows: её откроют «Блокнотом».

    python3 комплект/памятка-докладчику.py
"""
import pathlib
import re
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
КОЛОДА = ROOT / "презентация" / "Тілашар-защита.pptx"
ВЫХОД = ROOT / "комплект" / "ПАМЯТКА-ДОКЛАДЧИКА.txt"

ЗАГОЛОВКИ = [
    "Слайд 1 — Титул",
    "Слайд 2 — Как это появилось",
    "Слайд 3 — Зачем это нужно",
    "Слайд 4 — Что создано",
    "Слайд 5 — Как создано",
    "Слайд 6 — Что особенного",
    "Слайд 7 — Попробуйте сами",
    "Слайд 8 — Куда это может вырасти",
]


def заметки() -> list[str]:
    """Текст заметок по слайдам. Абзацы — это <a:p>, строки внутри — <a:t>."""
    z = zipfile.ZipFile(КОЛОДА)
    файлы = sorted(
        (n for n in z.namelist() if re.match(r"ppt/notesSlides/notesSlide\d+\.xml$", n)),
        key=lambda s: int(re.search(r"(\d+)", s.split("/")[-1]).group(1)),
    )
    итог = []
    for имя in файлы:
        xml = z.read(имя).decode("utf-8")
        абзацы = []
        for абзац in re.findall(r"<a:p>(.*?)</a:p>", xml, re.S):
            строка = "".join(re.findall(r"<a:t>(.*?)</a:t>", абзац, re.S))
            абзацы.append(строка.strip())
        текст = "\n".join(абзацы).strip()
        # Номер слайда в заметках стоит отдельным абзацем — он не нужен.
        текст = re.sub(r"^\d+\s*$", "", текст, flags=re.M).strip()
        итог.append(текст)
    return итог


ШАПКА = """\
ПАМЯТКА ДОКЛАДЧИКУ — ТІЛАШАР
Малышко Макар Евгеньевич, 6 «б» класс, №35 мектеп

Это заметки к каждому слайду: что сказать и о чём не забыть.
Они же лежат внутри Тілашар-защита.pptx («Вид» → «Заметки»).

ЧТО ВЗЯТЬ С СОБОЙ

  · Телефон с открытым приложением, заряженный.
  · Тілашар-защита.pdf — на флешке и в почте, на случай чужого компьютера.
  · все-слайды-защита.png — вся колода одной картинкой, для повторения.

ЗА ПЯТЬ МИНУТ ДО ВЫХОДА

  Открыть приложение, выбрать короткий урок и дойти до задания заранее —
  чтобы на сцене не искать. Проверить, что интернет не нужен: приложение
  работает и без него, но убедиться лучше заранее.

"""

ПОДВАЛ = """\

════════════════════════════════════════════════════════════════════════

ГЛАВНОЕ ОДНОЙ ФРАЗОЙ

  Казахский не сложнее других языков. Ученику мешало то, что он не мог
  нажать нужную букву. Это убрано — приложение засчитывает ответ,
  написанный русскими буквами, и показывает правильное написание.
"""


def main():
    куски = [ШАПКА]
    for заголовок, текст in zip(ЗАГОЛОВКИ, заметки()):
        if not текст:
            continue
        куски.append("═" * 72)
        куски.append(заголовок.upper())
        куски.append("")
        куски.append("\n".join("  " + с if с else "" for с in текст.split("\n")))
        куски.append("")
    куски.append(ПОДВАЛ)

    текст = "\n".join(куски)
    тело = текст.replace("\r\n", "\n").replace("\n", "\r\n")
    ВЫХОД.write_bytes(b"\xef\xbb\xbf" + тело.encode("utf-8"))
    print(f"  собрано: {ВЫХОД.name}  ({len(текст)} знаков, "
          f"{sum(1 for т in заметки() if т)} слайдов с заметками)")


if __name__ == "__main__":
    main()
